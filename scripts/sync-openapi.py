#!/usr/bin/env python3
"""Refresh api-reference/openapi.json from the cloud-api OpenAPI document.

The cloud-api document is generated by FastAPI and is correct but terse, so this
script tidies it for the docs site and leaves every path, parameter and schema
as the API defines it.

Usage, from the root of this repo:

    # from a cloud-api checkout (no database or running server needed)
    cd ../cloud-api && .venv/bin/python -c \
      "import json; from app.main import app; print(json.dumps(app.openapi()))" \
      > /tmp/cloud-api-openapi.json
    cd ../mintlify-docs && python3 scripts/sync-openapi.py /tmp/cloud-api-openapi.json

    # or from a running API
    curl -s https://<api host>/v1/openapi.json -o /tmp/cloud-api-openapi.json

What it changes:
  * servers: paths already start with /v1, so the server URL must not repeat it.
  * summaries: sentence case, with the acronyms FastAPI lower-cases put back.
  * tags: ordered and described, so the sidebar reads in the order people work.
  * operator-only and browser-only routes are hidden from the reference.

It also rewrites the "Endpoints" group of the "Cloud API" tab in docs.json, one
sub-group per tag in the order of TAGS, so a new endpoint appears in the sidebar
without editing docs.json by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "api-reference" / "openapi.json"
DOCS = ROOT / "docs.json"
SPEC = "api-reference/openapi.json"

SERVERS = [{"url": "https://api.farmgpu.com", "description": "Production"}]

# Sidebar order and the one line shown for each group.
TAGS = [
    ("Instances", "Create, list, control and terminate virtual machines and confidential trust domains."),
    ("Instance Types", "The catalogue of shapes you can launch, with their GPUs, vCPUs, memory and price."),
    ("Instance Availability", "Live capacity per instance type and region."),
    ("Regions", "Where instances can run."),
    ("Images", "Operating system images an instance can boot from."),
    ("Volumes", "Block volumes that attach to a running instance, with clone, resize and restore."),
    ("Filesystems", "Shared NFS filesystems with a hard quota, mounted from any of your instances."),
    ("SSH Keys", "Public keys installed on an instance at launch."),
    ("Startup Scripts", "Scripts run on first boot."),
    ("Operations", "The record of every asynchronous change. Poll one to follow a create, action or delete."),
    ("Webhooks", "Signed HTTP callbacks sent when an operation finishes."),
    ("Usage", "Metered usage and the account balance."),
    ("Quotas", "The limits on your account and how much of each is in use."),
    ("Attestation", "Reference values for verifying a confidential instance."),
    ("Auth", "API tokens and their scopes."),
    ("Health", "Service liveness."),
]

# Summaries FastAPI derives from function names that need a human touch.
SUMMARIES = {
    ("post", "/v1/instances"): "Create instance",
    ("post", "/v1/instances/{instance_id}/actions"): "Run instance action",
    ("get", "/v1/instances/{instance_id}/console"): "Get console URL",
    ("get", "/v1/instances/{instance_id}/attestation"): "Get instance attestation",
    ("get", "/v1/instance-availability/{instance_type}"): "Check availability for one type",
    ("get", "/v1/usage"): "Get usage summary",
    ("get", "/health"): "Health check",
}

ACRONYMS = {"Ssh": "SSH", "Url": "URL", "Api": "API", "Tdx": "TDX", "Nfs": "NFS", "Gpu": "GPU"}

# Routes that are not part of the customer API: the operator's host list and the
# HTML page the console URL opens in a browser.
HIDDEN = {
    ("get", "/v1/hosts"),
    ("get", "/v1/instances/{instance_id}/console/view"),
}

METHODS = {"get", "post", "put", "patch", "delete"}


def sentence_case(summary: str) -> str:
    words = summary.split()
    out = [words[0]] + [w.lower() if w not in ACRONYMS else w for w in words[1:]]
    return " ".join(ACRONYMS.get(w, ACRONYMS.get(w.capitalize(), w)) for w in out)


def main(src: str) -> None:
    doc = json.loads(Path(src).read_text())

    doc["servers"] = SERVERS
    doc["info"]["title"] = "FarmGPU Cloud API"

    seen_tags: set[str] = set()
    pages: dict[str, list[str]] = {}
    for path, item in doc["paths"].items():
        for method, op in item.items():
            if method not in METHODS:
                continue
            key = (method, path)
            op["summary"] = SUMMARIES.get(key) or sentence_case(op.get("summary", ""))
            if key in HIDDEN:
                op["x-hidden"] = True
                continue
            seen_tags.update(op.get("tags", []))
            pages.setdefault(op.get("tags", ["Other"])[0], []).append(f"{method.upper()} {path}")

    known = [name for name, _ in TAGS]
    unknown = sorted(seen_tags - set(known))
    if unknown:
        print(f"note: tags with no description yet (add them to TAGS): {', '.join(unknown)}", file=sys.stderr)
    doc["tags"] = [{"name": n, "description": d} for n, d in TAGS if n in seen_tags] + [
        {"name": n} for n in unknown
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, indent=2) + "\n")
    nav = json.loads(DOCS.read_text())
    tab = next(t for t in nav["navigation"]["tabs"] if t["tab"] == "Cloud API")
    endpoints = next(g for g in tab["groups"] if g["group"] == "Endpoints")
    endpoints["openapi"] = SPEC
    endpoints["pages"] = [
        {"group": name, "pages": pages[name]} for name in known + unknown + ["Other"] if name in pages
    ]
    DOCS.write_text(json.dumps(nav, indent=2) + "\n")

    ops = sum(1 for item in doc["paths"].values() for m in item if m in METHODS)
    print(f"wrote {SPEC}: {len(doc['paths'])} paths, {ops} operations, "
          f"version {doc['info']['version']}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
